    /** 按省份分组的全国城市列表（供城市选择器分组展示） */
    val groupedByProvince: Map<String, List<City>> by lazy {
        provinceCityNames.mapValues { (groupName, names) ->
            names.map { cityName ->
                val actualProvince = when (cityName) {
                    "北京" -> "北京市"
                    "上海" -> "上海市"
                    "天津" -> "天津市"
                    "重庆" -> "重庆市"
                    "香港" -> "香港特别行政区"
                    "澳门" -> "澳门特别行政区"
                    else -> groupName
                }
                City(
                    province = actualProvince,
                    name = cityName,
                    code = "${actualProvince}_$cityName"
                )
            }
        }
    }

    /** 扁平化的全国可选城市列表（供搜索过滤） */
    val selectable: List<City> by lazy {
        groupedByProvince.values.flatten()
    }

    /**
     * 判断坐标是否位于中国境内范围
     *
     * 过滤掉模拟器默认的海外坐标（如加州 37.42, -122.08），
     * 避免被强行按最近距离匹配到乌鲁木齐。
     */
    fun isInChina(latitude: Double, longitude: Double): Boolean {
        return latitude in 18.0..54.0 && longitude in 73.0..135.5
    }

    /**
     * 按坐标找最近的已知城市
     *
     * 用经纬度加权距离，纬度相差 1 度约 111km，
     * 中纬度地区经度 1 度约 85km，因此经度权重取 0.77。
     */
    fun nearest(latitude: Double, longitude: Double): City {
        return coordinateCities.minByOrNull { city ->
            val dLat = city.latitude - latitude
            val dLon = (city.longitude - longitude) * 0.77
            dLat * dLat + dLon * dLon
        } ?: default
    }
